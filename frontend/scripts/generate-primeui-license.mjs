import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const license = process.env.PRIMEUI_LICENSE ?? '';
const production = process.argv.includes('--production');

if (production && !license.trim()) {
  console.error('PRIMEUI_LICENSE is required for a production build.');
  process.exit(1);
}

if (license) {
  const primeNgConfig = import.meta.resolve('primeng/config');
  const configSource = readFileSync(new URL(primeNgConfig), 'utf8');
  // Use the same release date and verifier as the installed PrimeNG provider.
  const releaseDate = configSource.match(/const RELEASE_DATE = ["'](\d{4}-\d{2}-\d{2})["']/)?.[1];

  if (!releaseDate) {
    console.error('Could not determine the installed PrimeNG release date for license validation.');
    process.exit(1);
  }

  const requireFromPrimeNg = createRequire(primeNgConfig);
  const { verify } = requireFromPrimeNg('@primeui/license-manager');
  const result = await verify(license, { product: 'primeui', releaseDate });

  if (!result.valid) {
    console.error(`PRIMEUI_LICENSE was rejected by PrimeUI (${result.status}). ${result.message}`);
    process.exit(1);
  }
}

const configDirectory = new URL('../src/app/core/config/', import.meta.url);
mkdirSync(configDirectory, { recursive: true });
writeFileSync(
  new URL('primeui-license.ts', configDirectory),
  `// Generated by scripts/generate-primeui-license.mjs.\nexport const PRIMEUI_LICENSE = ${JSON.stringify(license)};\n`,
);
